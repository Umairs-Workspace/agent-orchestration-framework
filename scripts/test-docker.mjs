#!/usr/bin/env node
// scripts/test-docker.mjs — run the suite in a CAPPED Linux container instead of on this machine.
//
//   node scripts/test-docker.mjs --only <file>...          # focused run (the default use)
//   node scripts/test-docker.mjs --sharded [--jobs N]      # the whole tree, sharded, no cargo lane
//   node scripts/test-docker.mjs --exec <command>...        # any command in the same capped container
//   options: --cpus N (default 6) · --memory 8g · --rebuild
//
// Why: on the Windows control node every test pays Windows file-system costs (one stat walk of
// wiki/work measured ~1.1 CPU-s, mostly kernel), at normal priority, on every core — a run makes
// the machine unusable. In a container the work runs on Linux's file system, under a hard
// `--cpus`/`--memory` cap, with a fresh global home every run, so it can neither starve the host
// nor touch the real `~/.aof` or the live daemons' ports.
//
// How:
//   1. THE IMAGE holds only the dependency install. Its build context is the manifests and the
//      lockfile alone (written to .tmp/test-docker/context), so the install layer reruns only when
//      one of them changes; the tag is their hash. The install is the repo's own: Yarn's pinned
//      release, `--immutable`, lifecycle scripts off (`--mode=skip-build`), then the one reviewed
//      native build, `yarn rebuild node-pty` (it ships no linux-x64 prebuild).
//   2. THE SOURCE is this working tree as it stands — tracked files plus untracked, non-ignored
//      ones, so uncommitted work is tested — streamed into the container as a tar on stdin and
//      unpacked over the image's /work. A bind mount of C:\ would route every file call back
//      through the Windows file system, which is the cost this exists to avoid.
//   3. THE RUN is `scripts/test.mjs` (or `test-sharded.mjs --no-lanes`), its TAP streamed back,
//      its exit code this script's. The container is removed when it ends.
//
// What it cannot cover: the Windows-only branches (taskkill, win32 paths) and the desktop's Rust
// crates. Those still need a host run, rarely and focused.
import { spawn, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, rmSync, writeFileSync } from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";

const repo = path.resolve(path.dirname(fileURLToPath(import.meta.url)), "..");
const argv = process.argv.slice(2);
const flag = (name) => argv.includes(name);
const value = (name, fallback) => {
  const index = argv.indexOf(name);
  return index >= 0 && argv[index + 1] != null ? argv[index + 1] : fallback;
};
const NODE_IMAGE = "node:22.22.2-bookworm";
const YARN = ".yarn/releases/yarn-4.18.1.cjs";
const CPUS = value("--cpus", "6");
const MEMORY = value("--memory", "8g");

function run(command, args, options = {}) {
  const result = spawnSync(command, args, { cwd: repo, encoding: "utf8", windowsHide: true, ...options });
  if (result.error) throw result.error;
  return result;
}

// ---------------------------------------------------------------- 1. the dependency image
function workspaceManifests() {
  const out = [];
  for (const group of ["apps", "packages"]) {
    for (const entry of readdirSync(path.join(repo, group), { withFileTypes: true })) {
      const manifest = path.join(group, entry.name, "package.json");
      if (entry.isDirectory() && existsSync(path.join(repo, manifest))) out.push(manifest.split(path.sep).join("/"));
    }
  }
  return out.sort();
}

const DOCKERFILE = `# Generated by scripts/test-docker.mjs — the aof test image: Node, git, the native build tools
# node-pty compiles with, and the repo's own immutable install. No source: that arrives per run.
FROM ${NODE_IMAGE}
RUN apt-get update \\
 && apt-get install -y --no-install-recommends git python3 make g++ \\
 && rm -rf /var/lib/apt/lists/* \\
 && git config --global user.name "aof test" \\
 && git config --global user.email "aof-test@example.invalid" \\
 && git config --global init.defaultBranch main \\
 && git config --global --add safe.directory '*'
WORKDIR /work
COPY . /work/
ENV YARN_ENABLE_TELEMETRY=0 YARN_ENABLE_SCRIPTS=false
RUN node ${YARN} install --immutable --mode=skip-build \\
 && node ${YARN} rebuild node-pty \\
 && node -e "require('node:module').createRequire(require('node:path').resolve('packages/execution/package.json'))('node-pty'); console.log('node-pty loads')"
`;

function ensureImage() {
  const files = ["package.json", "yarn.lock", ".yarnrc.yml", YARN, ...workspaceManifests()];
  const hash = createHash("sha256");
  hash.update(DOCKERFILE);
  for (const file of files) hash.update(file).update(readFileSync(path.join(repo, file)));
  const tag = `aof-test:${hash.digest("hex").slice(0, 12)}`;
  const present = run("docker", ["image", "inspect", tag], { stdio: "ignore" }).status === 0;
  if (present && !flag("--rebuild")) return tag;
  const context = path.join(repo, ".tmp", "test-docker", "context");
  rmSync(context, { recursive: true, force: true });
  for (const file of files) {
    mkdirSync(path.dirname(path.join(context, file)), { recursive: true });
    cpSync(path.join(repo, file), path.join(context, file));
  }
  writeFileSync(path.join(context, "Dockerfile"), DOCKERFILE);
  console.error(`# test-docker: building ${tag} (the dependency install; reruns only when a manifest or the lockfile changes)`);
  const build = run("docker", ["build", "--tag", tag, context], { stdio: "inherit" });
  if (build.status !== 0) process.exit(build.status ?? 1);
  return tag;
}

// ---------------------------------------------------------------- 2. the source, as it stands
function sourceFiles() {
  const listed = run("git", ["ls-files", "-z", "--cached", "--others", "--exclude-standard"], { maxBuffer: 256 * 1024 * 1024 });
  if (listed.status !== 0) throw new Error(`git ls-files failed: ${listed.stderr}`);
  const files = listed.stdout.split("\0").filter((file) => file && existsSync(path.join(repo, file)));
  // Ignored, but read by suites: the built UI the surfaces serve, and the private-terms list the
  // scrub guards read. Each only when this checkout has it.
  for (const extra of ["apps/ui/dist", ".aof/private-terms.json"]) {
    if (existsSync(path.join(repo, extra))) files.push(extra);
  }
  return files;
}

// ---------------------------------------------------------------- 3. the run
function testCommand() {
  const exec = argv.indexOf("--exec");
  if (exec >= 0) return argv.slice(exec + 1);
  if (flag("--sharded")) {
    return ["node", "scripts/test-sharded.mjs", "--no-lanes", "--jobs", value("--jobs", String(Math.max(1, Number(CPUS) || 1)))];
  }
  const only = argv.indexOf("--only");
  if (only < 0 || argv.length <= only + 1) {
    console.error("usage: node scripts/test-docker.mjs --only <file>... | --sharded [--jobs N]  [--cpus N] [--memory 8g] [--rebuild]");
    process.exit(2);
  }
  const files = argv.slice(only + 1).filter((arg) => !arg.startsWith("--")).map((file) => file.split(path.sep).join("/"));
  return ["node", "scripts/test.mjs", "--only", ...files];
}

const tag = ensureImage();
const command = testCommand();
const files = sourceFiles();
console.error(`# test-docker: ${files.length} source files → ${tag}, --cpus ${CPUS} --memory ${MEMORY}: ${command.join(" ")}`);

// The container unpacks the tree over /work (keeping the image's node_modules), gives the run a
// fresh global home, and runs the suite at a lowered priority inside its own cap.
const inner = `set -e; tar -x -f - -C /work; export AOF_GLOBAL_HOME="$(mktemp -d)"; cd /work; exec nice -n 10 ${command.map((part) => `'${part.replaceAll("'", "'\\''")}'`).join(" ")}`;
const docker = spawn("docker", ["run", "--rm", "-i", "--cpus", CPUS, "--memory", MEMORY, "--network", "none", tag, "sh", "-c", inner], { cwd: repo, stdio: ["pipe", "inherit", "inherit"], windowsHide: true });
// The host's tar, fed the file list NUL-separated: the archive streams straight into the container.
const tar = spawn("tar", ["-c", "-f", "-", "--null", "-T", "-"], { cwd: repo, stdio: ["pipe", "pipe", "inherit"], windowsHide: true });
tar.stdout.pipe(docker.stdin);
tar.stdin.end(files.join("\0"));
tar.on("error", (error) => { console.error(`# test-docker: tar failed to start: ${error.message}`); docker.kill(); });
docker.on("exit", (code, signal) => process.exit(code ?? (signal ? 1 : 0)));
